function slugify(value) {
  return String(value ?? '')
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function objectId(prefix, index) {
  return new ObjectId(Buffer.from(`${prefix}${String(index).padStart(9, '0')}`))
}

const baselineDate = new Date(Date.UTC(2026, 0, 1))

const categories = categoryRows.map(([slug, name, subcategories], index) => ({
  _id: objectId('cat', index + 1),
  slug,
  name,
  description: null,
  imageUrl: null,
  parentId: null,
  subcategories,
  position: index + 1,
  active: true,
  createdAt: baselineDate,
  updatedAt: baselineDate,
}))

const categoryIdBySlug = new Map(categories.map((category) => [category.slug, category._id]))

const products = productRows.map((row, index) => {
  const { categorySlug, brand, reviews = [], ...rest } = row
  const createdAt = new Date(baselineDate.getTime() + index * 86400000)

  return {
    _id: objectId('prd', index + 1),
    status: 'ACTIVE',
    currency: 'USD',
    compareAtPriceCents: null,
    stock: 10,
    featured: false,
    badge: null,
    ...rest,
    categoryId: categoryIdBySlug.get(categorySlug),
    brand: { name: brand, slug: slugify(brand) },
    images: [{ url: productImages[index % productImages.length], position: 0 }],
    reviews: reviews.map((review, reviewIndex) => ({
      ...review,
      status: 'APPROVED',
      createdAt: new Date(createdAt.getTime() + (reviewIndex + 1) * 86400000),
    })),
    position: index + 1,
    createdAt,
    updatedAt: createdAt,
  }
})

const client = new MongoClient(env.mongoUri)

try {
  await client.connect()
  const db = client.db(env.mongoDbName)

  await Promise.all([
    db.collection('categories').deleteMany({}),
    db.collection('products').deleteMany({}),
  ])

  await db.collection('categories').insertMany(categories)
  await db.collection('products').insertMany(products)

  await db.collection('categories').createIndex({ slug: 1 }, { unique: true })
  await db.collection('categories').createIndex({ position: 1 })
  await db.collection('products').createIndex({ slug: 1 }, { unique: true })
  await db.collection('products').createIndex({ status: 1, categoryId: 1 })

  console.log(`Seeded ${categories.length} categories and ${products.length} products into ${db.databaseName}`)
} finally {
  await client.close()
}
